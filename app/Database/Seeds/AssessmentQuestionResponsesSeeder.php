<?php

namespace App\Database\Seeds;

use CodeIgniter\Database\Seeder;

class AssessmentQuestionResponsesSeeder extends Seeder
{
    public function run()
    {
        if ($this->db->table('assessment_question_responses')->countAllResults() > 0) {
            return;
        }

        $now = date('Y-m-d H:i:s');

        $submissions = $this->db->table('assessment_submissions s')
            ->select('
                s.id,
                s.assessment_id,
                s.is_graded,
                s.graded_at
            ')
            ->get()
            ->getResultArray();

        if (empty($submissions)) {
            return;
        }

        $rows = [];

        foreach ($submissions as $submission) {

            $questions = $this->db->table('assessment_questions')
                ->where('assessment_id', $submission['assessment_id'])
                ->orderBy('order_index', 'ASC')
                ->get()
                ->getResultArray();

            foreach ($questions as $question) {

                $selectedChoiceId = null;
                $responseText = null;
                $uploadedFileId = null;
                $score = null;
                $feedback = null;
                $isAutoGraded = 0;

                switch ($question['question_type']) {

                    case 'Multiple Choice':

                        $choice = $this->db->table('assessment_question_choices')
                            ->select('id')
                            ->where([
                                'question_id' => $question['id'],
                                'is_correct' => 1,
                            ])
                            ->get()
                            ->getRowArray();

                        if ($choice) {
                            $selectedChoiceId = $choice['id'];
                        }

                        $isAutoGraded = 1;

                        if ($submission['is_graded']) {
                            $score = $question['points'];
                        }

                        break;

                    case 'True/False':

                        $choice = $this->db->table('assessment_question_choices')
                            ->select('id')
                            ->where([
                                'question_id' => $question['id'],
                                'is_correct' => 1,
                            ])
                            ->get()
                            ->getRowArray();

                        if ($choice) {
                            $selectedChoiceId = $choice['id'];
                        }

                        $isAutoGraded = 1;

                        if ($submission['is_graded']) {
                            $score = $question['points'];
                        }

                        break;

                    case 'Short Answer':

                        $responseText = 'Sample short answer response.';

                        if ($submission['is_graded']) {
                            $score = $question['points'];
                            $feedback = 'Correct answer.';
                        }

                        break;

                    case 'Essay':

                        $responseText = 'This is a sample essay response generated by the database seeder for demonstration purposes.';

                        if ($submission['is_graded']) {
                            $score = max(0, $question['points'] - 1);
                            $feedback = 'Well written. Add more supporting details.';
                        }

                        break;

                    case 'Discussion':

                        $responseText = 'This is a sample discussion post.';

                        if ($submission['is_graded']) {
                            $score = $question['points'];
                            $feedback = 'Meaningful participation.';
                        }

                        break;

                    case 'File Upload':

                        $uploadedFileId = null;

                        if ($submission['is_graded']) {
                            $score = $question['points'];
                            $feedback = 'File submission accepted.';
                        }

                        break;

                    default:

                        $responseText = 'Sample response.';
                }

                $rows[] = [

                    'submission_id'      => $submission['id'],
                    'question_id'        => $question['id'],
                    'selected_choice_id' => $selectedChoiceId,
                    'response_text'      => $responseText,
                    'uploaded_file_id'   => $uploadedFileId,
                    'score'              => $score,
                    'feedback'           => $feedback,
                    'is_auto_graded'     => $isAutoGraded,
                    'graded_at'          => $submission['is_graded']
                        ? $submission['graded_at']
                        : null,
                    'created_at'         => $now,
                    'updated_at'         => null,
                ];
            }
        }

        if (! empty($rows)) {
            $this->db->table('assessment_question_responses')
                ->insertBatch($rows);
        }
    }
}
